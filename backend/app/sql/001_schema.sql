-- 001_schema.sql : tables, constraints, indexes
-- Layers: L0 raw (object store) | L1 staging | L2 canonical temporal | L3 tenant | cross-cutting

CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ============================================================ reference data
CREATE TABLE jurisdiction (
    jurisdiction_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                   VARCHAR(100) NOT NULL,
    type                   VARCHAR(20)  NOT NULL CHECK (type IN ('country','state','regulator')),
    parent_jurisdiction_id INT REFERENCES jurisdiction(jurisdiction_id),
    CONSTRAINT jurisdiction_not_self_parent CHECK (parent_jurisdiction_id IS DISTINCT FROM jurisdiction_id)
);
CREATE INDEX ix_jurisdiction_parent ON jurisdiction(parent_jurisdiction_id);

CREATE TABLE industry_sector (
    sector_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    nic_code    VARCHAR(10),
    description TEXT
);

CREATE TABLE source (
    source_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(150) NOT NULL,
    url             VARCHAR(500) NOT NULL UNIQUE,
    jurisdiction_id INT REFERENCES jurisdiction(jurisdiction_id),
    crawl_frequency VARCHAR(10) NOT NULL DEFAULT 'daily'
                    CHECK (crawl_frequency IN ('hourly','daily','weekly','monthly')),
    file_type       VARCHAR(10),
    is_active       BOOLEAN NOT NULL DEFAULT true,
    last_crawled_at TIMESTAMPTZ,
    last_doc_count  INT
);

-- ============================================================ L2 canonical, temporal
CREATE TABLE regulation (
    regulation_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                 VARCHAR(300) NOT NULL,
    short_name            VARCHAR(100),
    jurisdiction_id       INT NOT NULL REFERENCES jurisdiction(jurisdiction_id),
    instrument_type       VARCHAR(20) NOT NULL DEFAULT 'act'
                          CHECK (instrument_type IN ('act','rule','regulation','notification','circular','order','judgment')),
    parent_regulation_id  INT REFERENCES regulation(regulation_id),   -- Act -> Rules -> Circular
    category              VARCHAR(40),
    status                VARCHAR(15) NOT NULL CHECK (status IN ('active','repealed','draft')),
    first_effective_date  DATE
);
CREATE INDEX ix_regulation_jurisdiction ON regulation(jurisdiction_id);
CREATE INDEX ix_regulation_parent ON regulation(parent_regulation_id);
CREATE INDEX ix_regulation_title_trgm ON regulation USING gin (title gin_trgm_ops);

CREATE TABLE regulation_sector (
    regulation_id INT NOT NULL REFERENCES regulation(regulation_id) ON DELETE CASCADE,
    sector_id     INT NOT NULL REFERENCES industry_sector(sector_id),
    note          TEXT,
    PRIMARY KEY (regulation_id, sector_id)
);
CREATE INDEX ix_regulation_sector_sector ON regulation_sector(sector_id);

-- L1 staging: raw documents (declared before versions so versions can cite provenance)
CREATE TABLE regulatory_document (
    document_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id        INT NOT NULL REFERENCES source(source_id),
    title            VARCHAR(300) NOT NULL,
    published_date   DATE,
    url              VARCHAR(500) NOT NULL UNIQUE,
    content_hash     CHAR(64),                       -- sha256 of raw bytes: dedupe re-posted files
    raw_path         VARCHAR(500),                   -- L0 object-store key
    file_type        VARCHAR(10) CHECK (file_type IN ('HTML','PDF','XML','RSS','TXT','OTHER')),
    raw_text         TEXT,
    processed_status VARCHAR(15) NOT NULL DEFAULT 'pending'
                     CHECK (processed_status IN ('pending','processed','failed')),
    error_text       TEXT,
    retry_count      INT NOT NULL DEFAULT 0,
    fetched_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_doc_status ON regulatory_document(processed_status) WHERE processed_status <> 'processed';
CREATE INDEX ix_doc_hash ON regulatory_document(content_hash);

CREATE TABLE agent_run (
    run_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent          VARCHAR(30) NOT NULL CHECK (agent IN ('monitor','parse','extract','resolve','impact','obligation','task','notify','ask')),
    document_id    INT REFERENCES regulatory_document(document_id),
    model          VARCHAR(60),
    prompt_version VARCHAR(30),
    input_hash     CHAR(64),
    output_json    JSONB,
    status         VARCHAR(10) NOT NULL DEFAULT 'running' CHECK (status IN ('running','ok','failed')),
    error_text     TEXT,
    cost_usd       NUMERIC(10,5),
    started_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at    TIMESTAMPTZ
);
CREATE UNIQUE INDEX ux_agent_run_idem ON agent_run(agent, input_hash) WHERE status = 'ok' AND input_hash IS NOT NULL;
CREATE INDEX ix_agent_run_doc ON agent_run(document_id);

CREATE TABLE regulation_version (
    version_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regulation_id     INT NOT NULL REFERENCES regulation(regulation_id) ON DELETE CASCADE,
    version_number    VARCHAR(50) NOT NULL,
    -- valid time: when the rule is in force in the real world
    effective_from    DATE NOT NULL,
    effective_to      DATE,                              -- NULL = current
    -- transaction time: when we recorded / corrected it
    recorded_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    superseded_at     TIMESTAMPTZ,
    document_url      VARCHAR(500),
    source_document_id INT REFERENCES regulatory_document(document_id),
    created_by_run_id BIGINT REFERENCES agent_run(run_id),
    summary_text      TEXT,
    full_text         TEXT,
    change_summary    TEXT,
    change_type       VARCHAR(15) NOT NULL CHECK (change_type IN ('new','amendment','clarification','repeal')),
    confidence_score  NUMERIC(4,3) CHECK (confidence_score BETWEEN 0 AND 1),
    review_status     VARCHAR(15) NOT NULL DEFAULT 'approved'
                      CHECK (review_status IN ('needs_review','approved','rejected')),
    reviewed_by       INT,
    reviewed_at       TIMESTAMPTZ,
    summary_embedding vector(1024),
    CONSTRAINT rv_dates CHECK (effective_to IS NULL OR effective_to >= effective_from),
    -- no two approved, live versions of one regulation may overlap in valid time
    -- (versions awaiting review may overlap; approve_regulation_version() closes the predecessor)
    CONSTRAINT rv_no_overlap EXCLUDE USING gist (
        regulation_id WITH =,
        daterange(effective_from, effective_to, '[]') WITH &&
    ) WHERE (review_status = 'approved' AND superseded_at IS NULL)
);
CREATE INDEX ix_rv_temporal ON regulation_version(effective_from, effective_to);
CREATE INDEX ix_rv_reg ON regulation_version(regulation_id, effective_from);
CREATE INDEX ix_rv_review ON regulation_version(review_status) WHERE review_status = 'needs_review';

CREATE TABLE regulation_section (
    section_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id    INT NOT NULL REFERENCES regulation_version(version_id) ON DELETE CASCADE,
    section_no    VARCHAR(40) NOT NULL,
    heading       VARCHAR(500),
    body          TEXT NOT NULL,
    body_hash     CHAR(64) NOT NULL,                 -- cheap section-level diff
    embedding     vector(1024),
    UNIQUE (version_id, section_no)
);
CREATE INDEX ix_section_fts ON regulation_section USING gin (to_tsvector('english', coalesce(heading,'') || ' ' || body));

CREATE TABLE document_chunk (
    chunk_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id INT NOT NULL REFERENCES regulatory_document(document_id) ON DELETE CASCADE,
    ordinal     INT NOT NULL,
    text        TEXT NOT NULL,
    embedding   vector(1024),
    UNIQUE (document_id, ordinal)
);

CREATE TABLE document_regulation_link (
    document_id           INT NOT NULL REFERENCES regulatory_document(document_id) ON DELETE CASCADE,
    regulation_version_id INT NOT NULL REFERENCES regulation_version(version_id) ON DELETE CASCADE,
    relation_type         VARCHAR(15) NOT NULL DEFAULT 'describes'
                          CHECK (relation_type IN ('creates','amends','clarifies','repeals','describes')),
    confidence_score      NUMERIC(4,3) CHECK (confidence_score BETWEEN 0 AND 1),
    review_status         VARCHAR(15) NOT NULL DEFAULT 'approved'
                          CHECK (review_status IN ('needs_review','approved','rejected')),
    reviewed_by           INT,
    reviewed_at           TIMESTAMPTZ,
    PRIMARY KEY (document_id, regulation_version_id)
);

CREATE TABLE obligation (
    obligation_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligation_key           UUID NOT NULL DEFAULT gen_random_uuid(),   -- stable across amendments
    supersedes_obligation_id INT REFERENCES obligation(obligation_id),
    regulation_version_id    INT NOT NULL REFERENCES regulation_version(version_id) ON DELETE CASCADE,
    description              TEXT NOT NULL,
    frequency                VARCHAR(15) NOT NULL
                             CHECK (frequency IN ('one-time','annual','quarterly','monthly','ad-hoc')),
    -- calendar-anchored deadlines: {"type":"day_of_next_month","day":11} | {"type":"offset_days","days":60}
    -- | {"type":"fixed_date","month":9,"day":30} | {"type":"after_event","event":"agm","days":30}
    deadline_rule            JSONB,
    responsible_role         VARCHAR(50),
    penalty_severity         SMALLINT NOT NULL DEFAULT 3 CHECK (penalty_severity BETWEEN 1 AND 5),
    review_status            VARCHAR(15) NOT NULL DEFAULT 'approved'
                             CHECK (review_status IN ('needs_review','approved','rejected')),
    confidence_score         NUMERIC(4,3) CHECK (confidence_score BETWEEN 0 AND 1)
);
CREATE INDEX ix_obligation_version ON obligation(regulation_version_id);
CREATE INDEX ix_obligation_key ON obligation(obligation_key);

CREATE TABLE obligation_applicability (
    applicability_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligation_id    INT NOT NULL REFERENCES obligation(obligation_id) ON DELETE CASCADE,
    min_employees    INT CHECK (min_employees >= 0),
    max_employees    INT,
    min_turnover     NUMERIC(15,2) CHECK (min_turnover >= 0),
    max_turnover     NUMERIC(15,2),
    sector_id        INT REFERENCES industry_sector(sector_id),
    jurisdiction_id  INT REFERENCES jurisdiction(jurisdiction_id),
    condition_json   JSONB,                                   -- e.g. {"handles_personal_data": true}
    CONSTRAINT oa_emp CHECK (max_employees IS NULL OR min_employees IS NULL OR max_employees >= min_employees),
    CONSTRAINT oa_turn CHECK (max_turnover IS NULL OR min_turnover IS NULL OR max_turnover >= min_turnover)
);
CREATE INDEX ix_oa_obligation ON obligation_applicability(obligation_id);

CREATE TABLE compliance_calendar_rule (
    rule_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligation_key UUID,
    filing        VARCHAR(150) NOT NULL,
    authority     VARCHAR(100),
    form          VARCHAR(100),
    frequency     VARCHAR(15) NOT NULL CHECK (frequency IN ('monthly','quarterly','annual','one-time')),
    deadline_rule JSONB NOT NULL,
    valid_from    DATE NOT NULL,
    valid_to      DATE,
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

-- ============================================================ L3 tenant
CREATE TABLE company (
    company_id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    VARCHAR(200) NOT NULL,
    registration_number     VARCHAR(50) UNIQUE,
    primary_jurisdiction_id INT REFERENCES jurisdiction(jurisdiction_id),
    employee_count          INT CHECK (employee_count >= 0),
    annual_turnover         NUMERIC(15,2) CHECK (annual_turnover >= 0),
    handles_personal_data   BOOLEAN NOT NULL DEFAULT false,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE company_sector (
    company_id INT NOT NULL REFERENCES company(company_id) ON DELETE CASCADE,
    sector_id  INT NOT NULL REFERENCES industry_sector(sector_id),
    PRIMARY KEY (company_id, sector_id)
);

CREATE TABLE company_location (
    location_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      INT NOT NULL REFERENCES company(company_id) ON DELETE CASCADE,
    jurisdiction_id INT NOT NULL REFERENCES jurisdiction(jurisdiction_id),
    address         VARCHAR(300),
    is_headquarters BOOLEAN NOT NULL DEFAULT false
);
CREATE INDEX ix_location_company ON company_location(company_id);
CREATE UNIQUE INDEX ux_one_hq ON company_location(company_id) WHERE is_headquarters;

CREATE TABLE app_user (
    user_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(100) NOT NULL,
    email             VARCHAR(150) NOT NULL UNIQUE,
    password_hash     VARCHAR(255) NOT NULL,
    is_platform_admin BOOLEAN NOT NULL DEFAULT false,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE user_company_role (
    user_id    INT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    company_id INT NOT NULL REFERENCES company(company_id) ON DELETE CASCADE,
    role       VARCHAR(15) NOT NULL CHECK (role IN ('admin','manager','employee','consultant','viewer')),
    PRIMARY KEY (user_id, company_id)
);
CREATE INDEX ix_ucr_company ON user_company_role(company_id);

-- relevance of a regulation version to one company: drives the Change Feed
CREATE TABLE company_impact (
    impact_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      INT NOT NULL REFERENCES company(company_id) ON DELETE CASCADE,
    version_id      INT NOT NULL REFERENCES regulation_version(version_id) ON DELETE CASCADE,
    relevance_score NUMERIC(5,2) NOT NULL CHECK (relevance_score BETWEEN 0 AND 100),
    reason_json     JSONB,
    plain_summary   TEXT,
    status          VARCHAR(10) NOT NULL DEFAULT 'new' CHECK (status IN ('new','seen','dismissed','actioned')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id, version_id)
);
CREATE INDEX ix_impact_feed ON company_impact(company_id, status, relevance_score DESC);

CREATE TABLE company_obligation (
    company_obligation_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id            INT NOT NULL REFERENCES company(company_id) ON DELETE CASCADE,
    obligation_key        UUID NOT NULL,
    obligation_id         INT NOT NULL REFERENCES obligation(obligation_id),   -- current version of the obligation
    status                VARCHAR(15) NOT NULL DEFAULT 'active' CHECK (status IN ('active','completed','waived')),
    next_due_date         DATE,
    last_completed_date   DATE,
    risk_score            NUMERIC(5,2) CHECK (risk_score BETWEEN 0 AND 100),
    UNIQUE (company_id, obligation_key),
    UNIQUE (company_obligation_id, company_id)
);
CREATE INDEX ix_co_company_status ON company_obligation(company_id, status);
CREATE INDEX ix_co_due ON company_obligation(next_due_date) WHERE status = 'active';

CREATE TABLE task (
    task_id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_obligation_id INT NOT NULL,
    company_id            INT NOT NULL,                 -- denormalised for row level security
    title                 VARCHAR(200) NOT NULL,
    description           TEXT,
    period_start          DATE NOT NULL,
    period_end            DATE,
    due_date              DATE NOT NULL,
    status                VARCHAR(15) NOT NULL DEFAULT 'pending'
                          CHECK (status IN ('pending','in_progress','completed')),   -- "overdue" is derived (v_task_status)
    created_by_user_id    INT REFERENCES app_user(user_id),
    assigned_to_user_id   INT REFERENCES app_user(user_id),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at          TIMESTAMPTZ,
    FOREIGN KEY (company_obligation_id, company_id)
        REFERENCES company_obligation(company_obligation_id, company_id) ON DELETE CASCADE,
    UNIQUE (company_obligation_id, period_start),
    CONSTRAINT task_completed_has_ts CHECK ((status = 'completed') = (completed_at IS NOT NULL))
);
CREATE INDEX ix_task_due ON task(due_date, status);
CREATE INDEX ix_task_co ON task(company_obligation_id, status);
CREATE INDEX ix_task_open ON task(company_id, due_date) WHERE status <> 'completed';
CREATE INDEX ix_task_assignee ON task(assigned_to_user_id) WHERE status <> 'completed';

CREATE TABLE notification (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      INT NOT NULL REFERENCES company(company_id) ON DELETE CASCADE,
    user_id         INT REFERENCES app_user(user_id),
    kind            VARCHAR(20) NOT NULL CHECK (kind IN ('new_change','task_due','task_overdue','review_needed')),
    payload         JSONB NOT NULL,
    dedupe_key      VARCHAR(120) NOT NULL,                   -- outbox: never double-send
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at         TIMESTAMPTZ,
    read_at         TIMESTAMPTZ,
    UNIQUE (company_id, dedupe_key)
);
CREATE INDEX ix_notif_unsent ON notification(created_at) WHERE sent_at IS NULL;

-- ============================================================ audit (partitioned, append-only)
CREATE TABLE audit_log (
    log_id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    logged_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    entity_type VARCHAR(50) NOT NULL,
    entity_id   INT NOT NULL,
    company_id  INT,
    action      VARCHAR(10) NOT NULL CHECK (action IN ('create','update','delete')),
    user_id     INT,
    old_values  JSONB,
    new_values  JSONB,
    PRIMARY KEY (logged_at, log_id)
) PARTITION BY RANGE (logged_at);
CREATE TABLE audit_log_default PARTITION OF audit_log DEFAULT;
CREATE INDEX ix_audit_entity ON audit_log(entity_type, entity_id, logged_at DESC);
CREATE INDEX ix_audit_company ON audit_log(company_id, logged_at DESC);
